function pluralIndex(language, count) {
  if (language !== "pl") return count === 1 ? 0 : 1;
  if (count === 1) return 0;
  const tens = count % 100;
  return count % 10 >= 2 && count % 10 <= 4 && (tens < 12 || tens > 14) ? 1 : 2;
}

export function countLabel(language, key, count) {
  const base = (language || "en").split("-")[0];
  const forms = COUNTED[base] ?? COUNTED.en;
  return `${count} ${forms[key][pluralIndex(base, count)]}`;
}
